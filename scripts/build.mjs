// Builds the shipped plugin.js from src/ (src/plugin.js is the entry) with esbuild: one readable ES module, no minifying, so
// the signed file stays reviewable. `--check` fails when plugin.js is not exactly what src/ builds to.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const BANNER = "// Generated by `node scripts/build.mjs` from src/. Do not edit this file: edit src/ and rebuild.";
const esbuild = await import("esbuild");
const out = await esbuild.build({ entryPoints: [join(ROOT, "src/plugin.js")], bundle: true, format: "esm", target: "es2020", write: false, banner: { js: BANNER }, legalComments: "inline", charset: "utf8" });
const code = out.outputFiles[0].text;
const target = join(ROOT, "plugin.js");
if (process.argv.includes("--check")) {
  let now = ""; try { now = readFileSync(target, "utf8"); } catch { /* missing */ }
  if (now !== code) { console.error("plugin.js is NOT what src/ builds to: run node scripts/build.mjs"); process.exit(1); }
  console.log("plugin.js is exactly what src/ builds to");
} else { writeFileSync(target, code); console.log(`plugin.js written (${code.length} bytes)`); }
